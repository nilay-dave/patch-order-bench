"""Writes docs/results.md from docs/metrics.json, and verifies it is current.

A hand written results table is correct on the day it is written and silently
wrong after the next benchmark run. With --check it compares rather than
writes, which is what CI runs.

Every table carries the spread alongside the mean, because on this benchmark
the spread is the story as much as the mean is: across twelve seeds the
severity ordering's coverage of known exploited findings ranges over 0.65,
which is wide enough that a single run can land almost anywhere and a mean
presented alone would be read as more precise than it is.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
METRICS = ROOT / "docs" / "metrics.json"
TARGET = ROOT / "docs" / "results.md"


def render(data: dict) -> str:
    lines: list[str] = []
    add = lines.append
    headline = data["headline"]
    corpus = headline["corpus"]
    capacity = headline["capacity"]

    add("# Results")
    add("")
    add("Generated by `tools/generate_results_doc.py` from `docs/metrics.json`.")
    add("Reproduce with `make bench`.")
    add("")
    add("## Every figure here is a simulation")
    add("")
    add(data["note"])
    add("")

    add("## The corpus")
    add("")
    add(
        f"{corpus['findings']:,} findings over about {corpus['mean_distinct_cves']:,} CVEs, "
        f"{corpus['mean_kev_findings']:.0f} of them known exploited, averaged over {headline['seeds']} seeds. "
        f"{corpus['mean_already_past_window']:,} findings were already past their PCI window on day one, "
        "which is what a real backlog looks like and is why window attainment has a ceiling."
    )
    add("")
    add(
        f"The realized rank correlation between severity and exploitation probability came out at "
        f"{corpus['mean_realized_rank_correlation']:.3f}, and the realized share of CVEs at or above "
        f"EPSS 0.1 at {corpus['mean_share_epss_above_0_1']:.4f} against a sourced target of 0.0268. "
        "Both are reported because they are what the measurement ran on, rather than what was asked for."
    )
    add("")

    add("## The comparison")
    add("")
    add(
        f"A programme doing {capacity['per_week']:.0f} remediations a week for {capacity['weeks']} weeks, "
        f"which is {capacity['total_effort']:,.0f} in total against a backlog of {corpus['findings']:,}. "
        "Capacity has to bind, or there is nothing to prioritise."
    )
    add("")
    add(
        f"At this rate the most window compliance any ordering could achieve is "
        f"{corpus['mean_window_attainment_ceiling']:.0f} findings, and the attainment column is a share "
        "of that rather than of the backlog."
    )
    add("")
    add("| ordering | KEV coverage | spread over seeds | effort to 90% of KEV | window attainment | exposure removed |")
    add("| --- | --- | --- | --- | --- | --- |")
    for name, entry in headline["orderings"].items():
        effort = entry["effort_to_90pc_kev"]
        if effort["mean"] is None:
            shown = "never reached"
        elif effort["seeds_reached"] < effort["seeds_run"]:
            shown = f"{effort['mean']:.0f} ({effort['seeds_reached']}/{effort['seeds_run']} seeds)"
        else:
            shown = f"{effort['mean']:.0f}"
        add(
            f"| `{name}` | {entry['kev_coverage']:.3f} | {entry['kev_coverage_spread']:.3f} | {shown} | "
            f"{entry['window_attainment']:.3f} | {entry['exposure_removed']:.3f} |"
        )
    add("")

    best_kev = max(headline["orderings"], key=lambda n: headline["orderings"][n]["kev_coverage"])
    best_window = max(headline["orderings"], key=lambda n: headline["orderings"][n]["window_attainment"])
    cvss = headline["orderings"]["cvss"]
    shuffle = headline["orderings"]["random"]
    add(
        f"No ordering wins on both axes, and that is the result. `{best_kev}` covers the known exploited "
        f"findings best; `{best_window}` meets the most compliance windows; neither is second at the "
        "other's job. A programme has to choose which it is optimising, and most choose neither on "
        "purpose, because they rank by whatever the scanner printed."
    )
    add("")
    add(
        f"Ranking by severity covers {cvss['kev_coverage']:.3f} of the known exploited findings against "
        f"a shuffled backlog's {shuffle['kev_coverage']:.3f}. It is better than no ordering, and it is a "
        "long way behind putting the catalogue first."
    )
    add("")
    add("### How much to trust these")
    add("")
    widest = max(headline["orderings"], key=lambda n: headline["orderings"][n]["kev_coverage_spread"])
    add(
        f"The spread column is the range across {headline['seeds']} seeds, and for `{widest}` it is "
        f"{headline['orderings'][widest]['kev_coverage_spread']:.3f}, which is wider than most of the "
        "differences in the table. A single run can land almost anywhere inside that, which is why the "
        "benchmark averages and why a reader wanting a tighter figure should raise the seed count rather "
        "than quote one of these to three decimal places."
    )
    add("")

    add("## Does the conclusion survive its own assumption")
    add("")
    add(
        "The correlation between severity and exploitation probability is the parameter nothing in this "
        "project knows and everything depends on: at a correlation of 1 the two orderings are the same "
        "ordering. So it is swept rather than argued for."
    )
    add("")
    add("| correlation | realized | severity ordering | KEV first | shuffle | verdict |")
    add("| --- | --- | --- | --- | --- | --- |")
    for row in data["sensitivity_sweep"]["rows"]:
        add(
            f"| {row['cvss_epss_correlation']:.2f} | {row['realized_rank_correlation']:.3f} | "
            f"{row['cvss_kev_coverage']:.3f} | {row['kev_then_epss_kev_coverage']:.3f} | "
            f"{row['random_kev_coverage']:.3f} | {row['verdict']} |"
        )
    add("")
    verdicts = {row["verdict"] for row in data["sensitivity_sweep"]["rows"]}
    if verdicts <= {"exploitation ordering wins", "tied"}:
        add(
            "The conclusion holds across the range. It never flips, and at the top of the range the two "
            "converge, which is what should happen if the mechanism is the one claimed: at a perfect "
            "correlation the severity ordering and the exploitation ordering are the same ordering."
        )
    else:
        add("The conclusion does not hold across the range. See the verdict column for where it flips.")
    add("")

    add("## Runtime")
    add("")
    add("| findings | generate | slowest ordering | seconds |")
    add("| --- | --- | --- | --- |")
    for row in data["runtime"]:
        add(
            f"| {row['findings']:,} | {row['generate_seconds']:.2f}s | `{row['slowest_ordering']}` | "
            f"{row['slowest_seconds']:.3f}s |"
        )
    add("")
    biggest = data["runtime"][-1]
    add(
        f"Ranking and scheduling {biggest['findings']:,} findings takes "
        f"{biggest['slowest_seconds']:.1f} seconds for the slowest ordering. A ranking a programme "
        "cannot rerun weekly is a ranking it will stop rerunning."
    )
    add("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file on disk differs")
    args = parser.parse_args(argv)

    if not METRICS.is_file():
        print(f"{METRICS} is absent. Run: make bench", file=sys.stderr)
        return 1

    rendered = render(json.loads(METRICS.read_text(encoding="utf-8")))
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != rendered:
            print(f"{TARGET} is out of date. Run: python tools/generate_results_doc.py", file=sys.stderr)
            return 1
        print(f"{TARGET.name} matches the metrics")
        return 0

    TARGET.write_text(rendered, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
